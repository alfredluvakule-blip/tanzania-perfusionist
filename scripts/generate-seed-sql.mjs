// Generates supabase/seed.sql from src/lib/seed.ts so the referenced global history
// and research entries become editable rows in the CMS.
// Usage: node --experimental-strip-types scripts/generate-seed-sql.mjs
import { writeFileSync } from "node:fs";

const seed = await import("../src/lib/seed.ts");
const q = (v) =>
  v === null || v === undefined ? "null"
  : typeof v === "boolean" || typeof v === "number" ? String(v)
  : `'${String(v).replace(/'/g, "''")}'`;
const arr = (a) => (a && a.length ? `array[${a.map(q).join(",")}]::text[]` : "'{}'::text[]");
const json = (o) => `${q(JSON.stringify(o ?? []))}::jsonb`;

let out = `-- Generated by scripts/generate-seed-sql.mjs. Run after schema.sql.
-- Only real, referenced history and publications are seeded (status = published).
-- Placeholders (Tanzania / Africa) are published but flagged is_placeholder, so the public timeline
-- invites verified contributions. Editors replace them as sources are confirmed.
set client_min_messages = warning;
`;

for (const m of seed.milestones) {
  out += `insert into public.timeline_milestones (year, year_label, title, description, era, region, people, "references", verified, is_placeholder, status)
values (${[m.year, m.year_label, m.title, m.description, m.era, m.region, m.people].map(q).join(", ")}, ${json(m.references)}, ${m.verified}, ${!!m.is_placeholder}, 'published');\n`;
}
for (const p of seed.publications) {
  out += `insert into public.publications (title, authors, journal, year, doi, url, summary, key_findings, category, publication_type, content_kind, open_access, status)
values (${[p.title, p.authors, p.journal, p.year, p.doi, p.url, p.summary].map(q).join(", ")}, ${arr(p.key_findings)}, ${[p.category, p.publication_type, p.content_kind, !!p.open_access].map(q).join(", ")}, 'published');\n`;
}
for (const c of seed.caseReports) {
  out += `insert into public.case_reports (slug, title, age_group, procedure, sections, "references", author, published_at, tags, is_template, status)
values (${[c.slug, c.title, c.age_group, c.procedure].map(q).join(", ")}, ${q(JSON.stringify(c.sections))}::jsonb, ${arr(c.references)}, ${q(c.author)}, ${q(c.published_at)}, ${arr(c.tags)}, ${!!c.is_template}, 'published') on conflict (slug) do nothing;\n`;
}
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out);
console.log(`seed.sql: ${seed.milestones.length} milestones, ${seed.publications.length} publications, ${seed.caseReports.length} case template(s)`);
